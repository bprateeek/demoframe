#!/usr/bin/env node
import { existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { parse, stringify } from 'yaml';

const repoRoot = path.resolve(fileURLToPath(new URL('..', import.meta.url)));
const sourceConfig = path.join(repoRoot, 'examples/fieldwork-hero/demo.yml');
const expectedFormats = ['mp4', 'webm'];

function parseArgs(argv) {
  const args = {
    out: process.env.FIELDWORK_CINEMATIC_OUT || path.join(repoRoot, 'dist/fieldwork-cinematic'),
    download: true,
    configOnly: false,
  };

  for (let i = 0; i < argv.length; i += 1) {
    const arg = argv[i];
    if (arg === '--out' || arg === '-o') {
      args.out = path.resolve(argv[++i]);
    } else if (arg === '--no-download') {
      args.download = false;
    } else if (arg === '--config-only') {
      args.configOnly = true;
    } else if (arg === '--help' || arg === '-h') {
      printHelp();
      process.exit(0);
    } else {
      throw new Error(`unknown argument: ${arg}`);
    }
  }

  return args;
}

function printHelp() {
  console.log(`Generate the Fieldwork cinematic MP4/WebM sibling artifacts.

Usage:
  node scripts/fieldwork-cinematic-sibling.mjs [--out <dir>] [--no-download] [--config-only]

Defaults:
  --out dist/fieldwork-cinematic

The generated config derives from examples/fieldwork-hero/demo.yml, keeps the
same story and cinematic scene fields, switches to a 16:9 browser review frame,
and renders MP4/WebM at 854x480/30fps with motionBlur: cinematic.
`);
}

function cinematicScenes(scenes) {
  return scenes.map((scene) => {
    if (scene.type !== 'status-card') return scene;

    return {
      ...scene,
      subtitle: 'fieldwork-smoke #12 · main',
      branch: undefined,
      checks: ['Checks passed · Awaiting human review'],
      caption: undefined,
    };
  });
}

function cinematicConfig(source) {
  const config = structuredClone(source);
  config.title = `${source.title} (cinematic sibling)`;
  config.output = {
    ...config.output,
    format: expectedFormats,
    width: 854,
    fps: 30,
    budget: '25MB',
    quality: 'standard',
    motionBlur: 'cinematic',
  };
  delete config.output.displayWidth;

  config.frame = {
    type: 'browser',
    width: 854,
    height: 480,
    url: 'vps-fieldwork-smoke / fieldwork-smoke',
    title: 'Fieldwork cinematic review',
    chrome: 'thin',
  };
  config.brief = {
    ...config.brief,
    source:
      'Generated cinematic sibling derived from the Fieldwork phone hero; story, copy, composition, motion, and ambient are preserved for MP4/WebM review.',
    brand: { ...config.brief?.brand, frame: 'browser' },
  };
  config.scenes = cinematicScenes(config.scenes);
  return config;
}

function writeGeneratedConfig(outDir) {
  const configsDir = path.join(outDir, 'configs');
  mkdirSync(configsDir, { recursive: true });

  const sourceRaw = readFileSync(sourceConfig, 'utf8');
  const config = cinematicConfig(parse(sourceRaw));
  const configPath = path.join(configsDir, 'fieldwork-hero.cinematic.yml');
  writeFileSync(
    configPath,
    `# Generated by scripts/fieldwork-cinematic-sibling.mjs from examples/fieldwork-hero/demo.yml.\n` +
      `# Do not commit rendered MP4/WebM artifacts; regenerate them for visual review.\n` +
      stringify(config),
  );
  return configPath;
}

function cleanGeneratedOutputs(outDir) {
  for (const file of [
    'fieldwork-hero.cinematic.mp4',
    'fieldwork-hero.cinematic.webm',
    'report.json',
    'cinematic-report.json',
  ]) {
    rmSync(path.join(outDir, file), { force: true });
  }
  rmSync(path.join(outDir, 'preview'), { recursive: true, force: true });
  rmSync(path.join(outDir, 'configs', 'fieldwork-hero.cinematic.yml'), { force: true });
}

function run(command, args, cwd) {
  const result = spawnSync(command, args, { cwd, stdio: 'inherit' });
  if (result.error) throw result.error;
  if (result.status !== 0) {
    throw new Error(`${command} ${args.join(' ')} failed with exit code ${result.status}`);
  }
}

function assertClose(actual, expected, tolerance, label) {
  if (typeof actual !== 'number' || Math.abs(actual - expected) > tolerance) {
    throw new Error(`${label} expected about ${expected}, got ${actual}`);
  }
}

function assertReport(report, outDir) {
  const errors = report.errors || [];
  const warnings = report.warnings || [];
  const notices = report.notices || [];
  if (errors.length > 0) throw new Error(`render reported errors: ${JSON.stringify(errors)}`);
  if (warnings.length > 0) throw new Error(`render reported warnings: ${JSON.stringify(warnings)}`);
  const unexpectedNotices = notices.filter((notice) => notice.code !== 'cinematic.ambient.timeline');
  if (unexpectedNotices.length > 0) {
    throw new Error(`render reported unexpected notices: ${JSON.stringify(unexpectedNotices)}`);
  }
  if (report.brief?.mode !== 'user-confirmed' || report.brief?.confirmed !== true) {
    throw new Error('brief is not user-confirmed in report.json');
  }
  if (report.motionBlur?.requested !== 'cinematic') {
    throw new Error(`motionBlur.requested expected cinematic, got ${report.motionBlur?.requested}`);
  }
  if (!report.cinematic?.ambient) {
    throw new Error('expected cinematic ambient report semantics');
  }
  if (!report.previews?.some((file) => file.includes('final_readme_size'))) {
    throw new Error('expected preview/final_readme_size.png to be written');
  }

  const outputs = report.outputs || [];
  for (const format of expectedFormats) {
    const output = outputs.find((item) => item.format === format);
    if (!output) throw new Error(`missing ${format} output in report.json`);
    if (output.encoderProfile !== 'modern') {
      throw new Error(`${format} encoderProfile ${output.encoderProfile} did not match modern`);
    }
    if (!output.encoderSettings || typeof output.encoderSettings !== 'object') {
      throw new Error(`${format} did not record encoderSettings`);
    }
    if (output.motionBlur !== 'cinematic') throw new Error(`${format} output motionBlur was ${output.motionBlur}`);
    if (output.captureMode !== 'blurredCapture') throw new Error(`${format} captureMode was ${output.captureMode}`);
    if (output.withinBudget !== true) throw new Error(`${format} output is over budget`);
    if (output.hasAudio !== false) throw new Error(`${format} audio state was not the expected false value`);
    if (output.loopsForever !== null) {
      throw new Error(`${format} loopsForever should be null for native video containers, got ${output.loopsForever}`);
    }
    assertClose(output.width, 854, 2, `${format} width`);
    assertClose(output.height, 480, 2, `${format} height`);
    assertClose(output.fps, 30, 0.5, `${format} fps`);
    if (!output.durationS || output.durationS < 8) throw new Error(`${format} duration looks too short`);
    if (!existsSync(output.file)) throw new Error(`${format} output file is missing: ${output.file}`);
  }

  for (const item of report.motionBlur.outputs || []) {
    if (!expectedFormats.includes(item.format)) continue;
    if (item.motionBlur !== 'cinematic' || item.captureMode !== 'blurredCapture' || item.policy !== 'cinematic') {
      throw new Error(`unexpected motion blur policy for ${item.format}: ${JSON.stringify(item)}`);
    }
  }

  return {
    config: path.relative(outDir, report.config),
    report: 'report.json',
    previewDir: 'preview',
    outputs: expectedFormats.map((format) => {
      const output = outputs.find((item) => item.format === format);
      return {
        file: path.relative(outDir, output.file),
        format: output.format,
        width: output.width,
        height: output.height,
        durationS: output.durationS,
        fps: output.fps,
        sizeBytes: output.sizeBytes,
        budgetBytes: output.budgetBytes,
        withinBudget: output.withinBudget,
        loopsForever: output.loopsForever,
        hasAudio: output.hasAudio,
        encoderProfile: output.encoderProfile,
        encoderSettings: output.encoderSettings,
        motionBlur: output.motionBlur,
        captureMode: output.captureMode,
      };
    }),
    notices: notices.map((notice) => notice.code),
  };
}

function main() {
  const args = parseArgs(process.argv.slice(2));
  const outDir = path.resolve(args.out);
  const cli = path.join(repoRoot, 'dist/cli.js');
  if (!existsSync(cli)) {
    throw new Error('dist/cli.js is missing; run npm run build before generating cinematic siblings');
  }

  mkdirSync(outDir, { recursive: true });
  cleanGeneratedOutputs(outDir);
  const configPath = writeGeneratedConfig(outDir);
  if (args.configOnly) {
    console.log(`generated config: ${configPath}`);
    return;
  }

  const renderArgs = [
    cli,
    'render',
    configPath,
    '-o',
    outDir,
    '--encoder-profile',
    'modern',
    '--strict',
  ];
  if (!args.download) renderArgs.push('--no-download');

  run(process.execPath, renderArgs, repoRoot);

  const report = JSON.parse(readFileSync(path.join(outDir, 'report.json'), 'utf8'));
  const summary = {
    sourceConfig: path.relative(repoRoot, sourceConfig),
    generatedConfig: path.relative(outDir, configPath),
    frameConstraint:
      'The source Fieldwork README hero is a portrait phone frame. This sibling uses a generated 16:9 browser review frame to produce honest 854x480 MP4/WebM artifacts without adding a new stage model.',
    validation: assertReport(report, outDir),
  };
  const summaryFile = path.join(outDir, 'cinematic-report.json');
  writeFileSync(summaryFile, `${JSON.stringify(summary, null, 2)}\n`);

  console.log('\nFieldwork cinematic siblings complete');
  for (const output of summary.validation.outputs) {
    console.log(
      `  ${output.file}: ${output.format} ${output.width}x${output.height}, ` +
        `${output.durationS.toFixed(1)}s, ${output.fps}fps, ${output.encoderProfile}, ` +
        `${Math.round(output.sizeBytes / 1024)}KB`,
    );
  }
  console.log(`\nsummary: ${summaryFile}`);
}

try {
  main();
} catch (err) {
  console.error(`error: ${err.message}`);
  process.exit(1);
}
