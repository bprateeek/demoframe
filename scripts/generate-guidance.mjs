#!/usr/bin/env node
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(fileURLToPath(new URL('..', import.meta.url)));
const sourceFile = path.join(root, 'guidance', 'agent-guidance.md');
const generatedFile = path.join(root, 'src', 'generated', 'guidance.ts');
const check = process.argv.includes('--check');
const start = '<!-- demoframe:guidance-v2:start -->';
const end = '<!-- demoframe:guidance-v2:end -->';
const source = readFileSync(sourceFile, 'utf8').trim();
const generated = `// Generated by scripts/generate-guidance.mjs. Do not edit by hand.\nexport const GENERATED_AGENT_GUIDANCE = ${JSON.stringify(source)};\n`;
const targets = ['AGENTS.md', 'docs/llms.txt', 'skills/demoframe/SKILL.md'];

function withBlock(existing) {
  const block = `${start}\n${source}\n${end}`;
  const pattern = new RegExp(`${start}[\\s\\S]*?${end}`);
  return pattern.test(existing)
    ? existing.replace(pattern, block)
    : `${existing.trimEnd()}\n\n${block}\n`;
}

const mismatches = [];
if (!existsSync(generatedFile) || readFileSync(generatedFile, 'utf8') !== generated) {
  mismatches.push(path.relative(root, generatedFile));
  if (!check) {
    mkdirSync(path.dirname(generatedFile), { recursive: true });
    writeFileSync(generatedFile, generated);
  }
}
for (const target of targets) {
  const file = path.join(root, target);
  const existing = readFileSync(file, 'utf8');
  const expected = withBlock(existing);
  if (existing !== expected) {
    mismatches.push(target);
    if (!check) writeFileSync(file, expected);
  }
}

if (check && mismatches.length > 0) {
  console.error(`generated guidance is stale: ${mismatches.join(', ')}`);
  process.exit(1);
}
console.log(check ? 'generated guidance is current' : `generated guidance: ${mismatches.join(', ') || 'already current'}`);
