#!/usr/bin/env node
import { existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { spawnSync } from 'node:child_process';
import { parse, stringify } from 'yaml';

const repoRoot = path.resolve(fileURLToPath(new URL('..', import.meta.url)));
const sourceConfig = path.join(repoRoot, 'examples/fieldwork-hero/demo.yml');

function parseArgs(argv) {
  const args = {
    out: process.env.FIELDWORK_AB_OUT || path.join(repoRoot, 'dist/fieldwork-ab'),
    destination: 'github-readme',
    download: true,
  };

  for (let i = 0; i < argv.length; i += 1) {
    const arg = argv[i];
    if (arg === '--out' || arg === '-o') {
      args.out = path.resolve(argv[++i]);
    } else if (arg === '--for') {
      args.destination = argv[++i];
    } else if (arg === '--no-download') {
      args.download = false;
    } else if (arg === '--help' || arg === '-h') {
      printHelp();
      process.exit(0);
    } else {
      throw new Error(`unknown argument: ${arg}`);
    }
  }

  return args;
}

function printHelp() {
  console.log(`Generate the Fieldwork hero A/B artifact matrix.

Usage:
  node scripts/fieldwork-ab-matrix.mjs [--out <dir>] [--for <destination>] [--no-download]

Defaults:
  --out dist/fieldwork-ab
  --for github-readme
`);
}

function withoutCinematicFields(config) {
  const clone = structuredClone(config);
  clone.title = `${config.title} (old composition baseline)`;
  clone.scenes = clone.scenes.map((scene) => {
    const next = { ...scene };
    delete next.cinematic;
    return next;
  });
  return clone;
}

function writeGeneratedConfigs(outDir) {
  const configsDir = path.join(outDir, 'configs');
  mkdirSync(configsDir, { recursive: true });

  const sourceRaw = readFileSync(sourceConfig, 'utf8');
  const currentConfig = parse(sourceRaw);
  const oldConfig = withoutCinematicFields(currentConfig);

  const oldConfigPath = path.join(configsDir, 'fieldwork-old-comp.yml');
  const currentConfigPath = path.join(configsDir, 'fieldwork-new-comp.yml');
  writeFileSync(
    oldConfigPath,
    `# Generated by scripts/fieldwork-ab-matrix.mjs from examples/fieldwork-hero/demo.yml.\n` +
      `# This baseline removes scene.cinematic fields only; it does not depend on git history.\n` +
      stringify(oldConfig),
  );
  writeFileSync(
    currentConfigPath,
    `# Generated by scripts/fieldwork-ab-matrix.mjs from examples/fieldwork-hero/demo.yml.\n` +
      `# This is the current Fieldwork composition used for encoder comparison cells.\n` +
      sourceRaw,
  );

  return { oldConfigPath, currentConfigPath };
}

function run(command, args, cwd) {
  const result = spawnSync(command, args, { cwd, stdio: 'inherit' });
  if (result.error) throw result.error;
  if (result.status !== 0) {
    throw new Error(`${command} ${args.join(' ')} failed with exit code ${result.status}`);
  }
}

function assertReport(cell, report, destination) {
  const errors = report.errors || [];
  const warnings = report.warnings || [];
  if (errors.length > 0) throw new Error(`${cell.id} reported errors: ${JSON.stringify(errors)}`);
  if (warnings.length > 0) throw new Error(`${cell.id} reported warnings: ${JSON.stringify(warnings)}`);
  if (report.brief?.mode !== 'user-confirmed' || report.brief?.confirmed !== true) {
    throw new Error(`${cell.id} brief is not user-confirmed in report.json`);
  }

  const output = report.outputs?.[0];
  if (!output) throw new Error(`${cell.id} did not produce an output entry`);
  if (output.encoderProfile !== cell.encoderProfile) {
    throw new Error(`${cell.id} encoderProfile ${output.encoderProfile} did not match ${cell.encoderProfile}`);
  }
  if (!output.encoderSettings || typeof output.encoderSettings !== 'object') {
    throw new Error(`${cell.id} did not record encoderSettings`);
  }
  if (output.withinBudget !== true) throw new Error(`${cell.id} output is over budget`);
  if (output.loopsForever !== true) throw new Error(`${cell.id} output does not loop forever`);
  if (!output.width || !output.height) throw new Error(`${cell.id} output dimensions were not detected`);
  if (!output.durationS || output.durationS < 8) throw new Error(`${cell.id} duration looks too short`);
  if (!report.previews?.some((file) => file.includes('readme_size'))) {
    throw new Error(`${cell.id} did not write a README-size preview still`);
  }
  if (destination === 'github-readme' && output.format !== 'webp') {
    throw new Error(`${cell.id} expected a WebP output for github-readme, got ${output.format}`);
  }
  if (cell.expectCinematic && !report.cinematic?.ambient) {
    throw new Error(`${cell.id} expected cinematic report semantics`);
  }
  if (!cell.expectCinematic && report.cinematic) {
    throw new Error(`${cell.id} unexpectedly reported cinematic semantics`);
  }
}

function relative(outDir, file) {
  return path.relative(outDir, file);
}

function summaryFor(cell, report, outDir) {
  const output = report.outputs[0];
  return {
    id: cell.id,
    comparisonRole: cell.comparisonRole,
    config: relative(outDir, cell.config),
    report: relative(outDir, path.join(cell.out, 'report.json')),
    previewDir: relative(outDir, path.join(cell.out, 'preview')),
    output: {
      file: relative(outDir, output.file),
      format: output.format,
      width: output.width,
      height: output.height,
      durationS: output.durationS,
      fps: output.fps,
      sizeBytes: output.sizeBytes,
      withinBudget: output.withinBudget,
      loopsForever: output.loopsForever,
      encoderProfile: output.encoderProfile,
      encoderSettings: output.encoderSettings,
    },
  };
}

function main() {
  const args = parseArgs(process.argv.slice(2));
  const outDir = path.resolve(args.out);
  const cli = path.join(repoRoot, 'dist/cli.js');
  if (!existsSync(cli)) {
    throw new Error('dist/cli.js is missing; run npm run build before generating the matrix');
  }

  mkdirSync(outDir, { recursive: true });
  const { oldConfigPath, currentConfigPath } = writeGeneratedConfigs(outDir);
  const cells = [
    {
      id: 'legacy-old-comp',
      comparisonRole: 'A/B #1 baseline: old composition with the legacy encoder',
      config: oldConfigPath,
      encoderProfile: 'legacy',
      expectCinematic: false,
    },
    {
      id: 'legacy-new-comp',
      comparisonRole: 'A/B #1 treatment and A/B #2 baseline: current cinematic composition with the legacy encoder',
      config: currentConfigPath,
      encoderProfile: 'legacy',
      expectCinematic: true,
    },
    {
      id: 'modern-new-comp',
      comparisonRole: 'A/B #2 treatment: current cinematic composition with the modern encoder',
      config: currentConfigPath,
      encoderProfile: 'modern',
      expectCinematic: true,
    },
  ].map((cell) => ({ ...cell, out: path.join(outDir, cell.id) }));

  const summaries = [];
  for (const cell of cells) {
    rmSync(cell.out, { recursive: true, force: true });
    const renderArgs = [
      cli,
      'render',
      cell.config,
      '-o',
      cell.out,
      '--for',
      args.destination,
      '--encoder-profile',
      cell.encoderProfile,
      '--strict',
    ];
    if (!args.download) renderArgs.push('--no-download');

    console.log(`\n=== ${cell.id} ===`);
    run(process.execPath, renderArgs, repoRoot);

    const report = JSON.parse(readFileSync(path.join(cell.out, 'report.json'), 'utf8'));
    assertReport(cell, report, args.destination);
    summaries.push(summaryFor(cell, report, outDir));
  }

  const summary = {
    sourceConfig: path.relative(repoRoot, sourceConfig),
    destination: args.destination,
    matrix: summaries,
    comparisons: [
      {
        id: 'composition-delta',
        compare: ['legacy-old-comp', 'legacy-new-comp'],
        isolates: 'scene.cinematic composition/motion/ambient changes while holding encoderProfile=legacy',
      },
      {
        id: 'encoder-delta',
        compare: ['legacy-new-comp', 'modern-new-comp'],
        isolates: 'encoder profile changes while holding the current Fieldwork composition fixed',
      },
      {
        id: 'cinematic-later',
        status: 'placeholder',
        note: 'Motion blur remains off in this matrix; do not treat this PR as a blur implementation.',
      },
    ],
  };
  const summaryFile = path.join(outDir, 'matrix-report.json');
  writeFileSync(summaryFile, `${JSON.stringify(summary, null, 2)}\n`);

  console.log('\nFieldwork A/B matrix complete');
  for (const cell of summaries) {
    console.log(
      `  ${cell.id}: ${cell.output.format} ${cell.output.width}x${cell.output.height}, ` +
        `${cell.output.durationS.toFixed(1)}s, ${cell.output.encoderProfile}, ` +
        `${Math.round(cell.output.sizeBytes / 1024)}KB`,
    );
  }
  console.log(`\nsummary: ${summaryFile}`);
}

try {
  main();
} catch (err) {
  console.error(`error: ${err.message}`);
  process.exit(1);
}
